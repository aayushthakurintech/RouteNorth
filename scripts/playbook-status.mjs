// Builds docs/FEATURE_PLAYBOOK_STATUS.md from docs/playbook/items.json (every idea in the
// Feature Playbook PDF) and docs/playbook/status.json (our status for each idea).
// Run: node scripts/playbook-status.mjs        (add --check to fail when an item has no status)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "docs");
const items = JSON.parse(readFileSync(join(root, "playbook", "items.json"), "utf8"));
const status = JSON.parse(readFileSync(join(root, "playbook", "status.json"), "utf8"));

const LABEL = {
  done: "Done",
  partial: "Partly built",
  external: "Needs outside accounts or hardware",
  skip: "Chosen not to build",
  todo: "Not started",
};
const ICON = { done: "✅", partial: "🟡", external: "🔌", skip: "➖", todo: "⬜" };

let missing = 0;
const counts = { done: 0, partial: 0, external: 0, skip: 0, todo: 0 };
for (const it of items) {
  const st = status[it.id];
  if (!st) { missing++; counts.todo++; continue; }
  counts[st.s]++;
}

let out = `# RouteNorth Feature Playbook: status of every idea\n\n`;
out += `Source: *RouteNorth Feature Playbook* (PDF, ${items.length} numbered ideas). This file is generated by \`node scripts/playbook-status.mjs\` from \`docs/playbook/status.json\`; edit that file, not this one.\n\n`;
out += `| Status | Count |\n| --- | ---: |\n`;
for (const k of ["done", "partial", "external", "skip", "todo"]) out += `| ${ICON[k]} ${LABEL[k]} | ${counts[k]} |\n`;
out += `\n- **Done**: built, with tests or a manual run behind it.\n- **Partly built**: the useful core works; the note says what is missing.\n- **Needs outside accounts or hardware**: the in-product side is built (settings, adapter, queue), but it cannot be verified or switched on without a third-party account, credentials or a physical device. Nothing here pretends to be connected.\n- **Chosen not to build**: left out on purpose; the note says why (the Playbook itself says "do not build them all").
- **Not started**: not built yet.\n\n`;

let group = "", section = "";
for (const it of items) {
  if (it.group !== group) { group = it.group; out += `\n## ${group}\n`; section = ""; }
  if (it.section !== section) { section = it.section; out += `\n### ${section}\n\n| # | Idea | Status | Where / note |\n| ---: | --- | --- | --- |\n`; }
  const st = status[it.id] ?? { s: "todo", note: "" };
  out += `| ${it.n} | ${it.text.replace(/\|/g, "\\|")} | ${ICON[st.s]} ${LABEL[st.s]} | ${(st.note ?? "").replace(/\|/g, "\\|")} |\n`;
}
writeFileSync(join(root, "FEATURE_PLAYBOOK_STATUS.md"), out);
console.log(Object.entries(counts).map(([k, v]) => `${k}: ${v}`).join("  "));
if (process.argv.includes("--check") && missing) { console.error(`${missing} items have no status`); process.exit(1); }
